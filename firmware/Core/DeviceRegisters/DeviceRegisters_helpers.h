/* Generic helpers (token-pasting)
 * Usage:
 *   REG_ADDR(CURRENT_POS_16, motor0)  // motor0 is 0-based
 *   REG_OFFSET(CURRENT_POS_16, motor0)
 *   REG_SIZE_WORDS(CURRENT_POS_16)
 *   REG_SIZE_BYTES(CURRENT_POS_16)
 */
#define REG_SIZE_WORDS(name)     (REG_SIZE_##name)
#define REG_SIZE_BYTES(name)     ((uint16_t)REG_SIZE_##name * 2u)
#define REG_ADDR(name, motor0)   ((uint16_t)(REG_BASE_##name + (uint16_t)((REG_PER_MOTOR_##name) ? ((uint16_t)(motor0) * (uint16_t)REG_SIZE_##name) : 0u)))
#define REG_OFFSET(name, motor0) ((uint16_t)((REG_PER_MOTOR_##name) ? ((uint16_t)(motor0) * (uint16_t)REG_SIZE_##name) : 0u))

